import { expect, test } from '@playwright/test';
import { execFileSync } from 'node:child_process';

test('centralizes Sala payment registration and reversal in Finance while Professor only sees state', async ({ page }) => {
  test.setTimeout(60000);
  execFileSync('pnpm', ['--filter', '@athleta/api', 'exec', 'tsx', '-e', `
    import { PrismaClient } from '@prisma/client';
    const prisma = new PrismaClient();
    async function clean() {
      const people = await prisma.person.findMany({ where: { normalizedDni: { in: ['40880000', '40880001', '40880002'] } }, select: { id: true } });
      const personId = { in: people.map(person => person.id) };
      await prisma.salaPaymentReversal.deleteMany({ where: { payment: { personId } } });
      await prisma.salaPaymentAllocation.deleteMany({ where: { payment: { personId } } });
      await prisma.salaPayment.deleteMany({ where: { personId } });
    }
    clean().finally(() => prisma.$disconnect());
  `], { cwd: '../..', stdio: 'inherit' });
  for (const kind of ['student-follow-up', 'sala']) execFileSync('pnpm', ['--filter', '@athleta/api', 'exec', 'tsx', 'scripts/e2e-fixture.ts', kind], { cwd: '../..', stdio: 'inherit' });
  await page.goto('/login');
  await page.getByLabel('Email').fill('e2e.sala@athleta.test');
  await page.getByLabel('Contraseña').fill('ValidPass1!');
  await page.getByRole('button', { name: /Ingresar/ }).click();
  await expect(page).toHaveURL('/');
  const session = (await (await page.request.get('/api/auth/session')).json()).data;
  const createdMethod = await page.request.post('/api/finance/payment-methods', { headers: { 'x-csrf-token': session.csrfToken }, data: { name: `Efectivo Bloque4 ${Date.now()}` } });
  expect(createdMethod.status()).toBe(201);
  const method = (await createdMethod.json()).data;
  await page.goto('/students');
  const student = page.getByRole('row').filter({ hasText: 'Alumno0 FollowUpE2E' });
  await expect(student.getByText('Sin vigencia', { exact: true })).toBeVisible();
  const financeHref = await student.getByRole('link', { name: 'Renovar' }).getAttribute('href');
  await student.getByRole('link', { name: 'Renovar' }).click();
  await expect(page).toHaveURL(financeHref!);
  await expect(page.getByRole('heading', { name: 'Historial de pagos', exact: true })).toBeVisible();
  await expect(page.getByLabel('Mes a pagar')).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Registrar renovación', exact: true })).toBeVisible();
  await expect(page.getByText('Alumno0 FollowUpE2E', { exact: true })).toBeVisible();
  await expect(page.getByLabel(/^Precio/)).toHaveValue('1000');
  await page.getByLabel(/^Precio/).fill('900');
  await expect(page.getByRole('button', { name: /^Registrar pago/ })).toBeDisabled();
  await page.getByLabel(/^Motivo de ajuste/).fill('Descuento acordado E2E');
  await expect(page.getByLabel('Fecha de cobro')).not.toHaveValue('');
  await expect(page.getByText(/Con este pago:/)).toBeVisible();
  await page.getByRole('button', { name: method.name, exact: true }).click();
  await page.getByRole('button', { name: /^Registrar pago/ }).click();
  await expect(page.getByText('Pago registrado correctamente.')).toBeVisible();
  await expect(page.getByRole('button', { name: '+ Registrar renovación' })).toHaveAttribute('aria-expanded', 'false');
  await expect(page.getByRole('heading', { name: 'Historial de pagos' })).toBeVisible();
  await page.getByRole('link', { name: 'Ver ficha' }).click();
  await expect(page.getByText(/^Vigente hasta /)).toBeVisible();
  await expect(page.getByLabel('Fecha de cobro')).toHaveCount(0);
  await page.getByRole('link', { name: 'Ver pagos', exact: true }).click();
  await page.getByRole('button', { name: 'Revertir', exact: true }).click();
  const dialog = page.getByRole('alertdialog');
  await expect(dialog.getByRole('button', { name: 'Revertir pago' })).toBeDisabled();
  await dialog.getByLabel('Motivo de reversión').fill('Cobro duplicado E2E');
  await dialog.getByRole('button', { name: 'Revertir pago' }).click();
  await expect(page.getByRole('row').filter({ hasText: method.name }).getByText('Revertido', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Ver ficha' }).click();
  await expect(page.getByText('Sin vigencia', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: /Cerrar sesión/ }).click();
  await expect(page).toHaveURL('/login');
  await page.goto('/login');
  await page.getByLabel('Email').fill('e2e.student-follow-up@athleta.test');
  await page.getByLabel('Contraseña').fill('ValidPass1!');
  const loginResponse = page.waitForResponse(response => response.url().endsWith('/api/auth/login') && response.request().method() === 'POST');
  await page.getByRole('button', { name: /Ingresar/ }).click();
  expect((await loginResponse).status()).toBe(200);
  await expect(page).toHaveURL('/');
  await page.getByRole('link', { name: 'Alumnos', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Renovar' })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Ver pagos', exact: true })).toHaveCount(0);
  await page.getByRole('row').filter({ hasText: 'Alumno0 FollowUpE2E' }).getByRole('link', { name: 'Ver ficha' }).click();
  await expect(page).toHaveURL(/\/sala\/people\/[0-9a-f-]+$/);
  await expect(page.getByRole('heading', { name: 'Alumno0 FollowUpE2E', exact: true })).toBeVisible();
  await expect(page.getByText('Sin vigencia', { exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Pagos', exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Gestionar pagos' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Revertir', exact: true })).toHaveCount(0);
});
